#!/usr/bin/env python3
"""Touchpad gesture settings for the Omarchy plugin nox.trackpad-gestures.

The bar panel and this script are the only writers. Settings live in
~/.config/omarchy/trackpad-gestures.json; the Hyprland Lua the plugin needs is
generated from them into ~/.config/hypr/trackpad_gestures.lua, which the plugin
includes from ~/.config/hypr/hyprland.lua so a config reload keeps the gesture.

Usage:
    gestures.py state               print the settings as JSON
    gestures.py get <key>           print one setting
    gestures.py apply               regenerate the Lua, reload Hyprland if it changed
    gestures.py set <key> <value>   change one setting, then apply
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

HOME = Path.home()
CONFIG = HOME / ".config/omarchy/trackpad-gestures.json"
LUA = HOME / ".config/hypr/trackpad_gestures.lua"
HYPRLAND_LUA = HOME / ".config/hypr/hyprland.lua"

INCLUDE_MARKER = "-- Trackpad gestures (Omarchy plugin nox.trackpad-gestures)"
INCLUDE_LINE = 'require("hypr.trackpad_gestures")'

DEFAULTS = {
    "enabled": True,   # the swipe does anything at all
    "fingers": 4,      # how many fingers it takes
    "invert": False,   # false: fingers left = next workspace, like macOS
    "distance": 300,   # finger travel in px that makes a full workspace switch
    "animation": True, # slide the workspaces home when the fingers lift
}

TRUE_WORDS = {"1", "true", "yes", "on"}
FALSE_WORDS = {"0", "false", "no", "off"}


class BadValue(Exception):
    pass


def as_bool(value):
    if isinstance(value, bool):
        return value
    word = str(value).strip().lower()
    if word in TRUE_WORDS:
        return True
    if word in FALSE_WORDS:
        return False
    raise BadValue("expected true or false, got %r" % value)


def as_distance(value):
    try:
        distance = int(str(value).strip())
    except ValueError:
        raise BadValue("expected a whole number, got %r" % value) from None
    if not 100 <= distance <= 2000:
        raise BadValue("distance must be between 100 and 2000")
    return distance


def as_fingers(value):
    try:
        fingers = int(str(value).strip())
    except ValueError:
        raise BadValue("expected 3 or 4, got %r" % value) from None
    if fingers not in (3, 4):
        raise BadValue("fingers must be 3 or 4")
    return fingers


VALIDATORS = {
    "enabled": as_bool,
    "fingers": as_fingers,
    "invert": as_bool,
    "distance": as_distance,
    "animation": as_bool,
}


def sanitize(raw):
    """Defaults plus whatever of `raw` makes sense, never a bad value."""
    settings = dict(DEFAULTS)
    if not isinstance(raw, dict):
        return settings
    for key, validate in VALIDATORS.items():
        if key not in raw:
            continue
        try:
            settings[key] = validate(raw[key])
        except BadValue:
            pass
    return settings


def load():
    try:
        return sanitize(json.loads(CONFIG.read_text()))
    except (OSError, ValueError):
        return dict(DEFAULTS)


def save(settings):
    CONFIG.parent.mkdir(parents=True, exist_ok=True)
    temporary = CONFIG.with_name(CONFIG.name + ".tmp")
    temporary.write_text(json.dumps(settings, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, CONFIG)


def lua_bool(value):
    return "true" if value else "false"


def render(settings):
    head = [
        "-- Trackpad gestures, generated by the Omarchy plugin",
        "-- nox.trackpad-gestures. Change them from its panel in the bar or with",
        "-- `gestures.py set <key> <value>`; this file is rewritten on every change.",
        "",
    ]
    if not settings["enabled"]:
        return "\n".join(head + ["-- The swipe is switched off in the panel.", ""])

    body = [
        "-- %d fingers, swiping %s between workspaces."
        % (settings["fingers"], "backwards" if settings["invert"] else "forwards"),
        'hl.gesture({ fingers = %d, direction = "horizontal", action = "workspace" })'
        % settings["fingers"],
        "",
        "hl.config({",
        "  gestures = {",
        "    workspace_swipe_invert = %s," % lua_bool(settings["invert"]),
        "    workspace_swipe_distance = %d," % settings["distance"],
        "  },",
        "})",
        "",
    ]

    if settings["animation"]:
        # The parent leaf of workspacesIn/workspacesOut: Omarchy switches these
        # off for instant SUPER+1/2/3 jumps, but the swipe needs the short slide
        # home when the fingers lift, or it snaps the last half screen.
        body += [
            'hl.animation({ leaf = "workspaces", enabled = true, speed = 8, bezier = "easeOutQuint", style = "slide" })',
            "",
        ]
    else:
        body += ['hl.animation({ leaf = "workspaces", enabled = false })', ""]

    return "\n".join(head + body)


def write_if_changed(path, content):
    try:
        if path.read_text() == content:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(content)
    os.replace(temporary, path)
    return True


def ensure_include():
    """hyprland.lua must require the generated file, or nothing loads it."""
    try:
        text = HYPRLAND_LUA.read_text()
    except OSError:
        return False
    if INCLUDE_LINE in text:
        return False
    separator = "" if text.endswith("\n") or not text else "\n"
    addition = "%s\n%s\n%s\n" % (separator, INCLUDE_MARKER, INCLUDE_LINE)
    return write_if_changed(HYPRLAND_LUA, text + addition)


def reload_hyprland():
    try:
        result = subprocess.run(
            ["hyprctl", "reload"], capture_output=True, text=True, timeout=15
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        print("Hyprland reload failed: %s" % error, file=sys.stderr)
        return False
    if result.returncode != 0:
        print("Hyprland reload failed: %s" % result.stderr.strip(), file=sys.stderr)
        return False
    try:
        errors = subprocess.run(
            ["hyprctl", "configerrors"], capture_output=True, text=True, timeout=15
        )
    except (OSError, subprocess.TimeoutExpired):
        return True
    message = errors.stdout.strip()
    if message:
        print("Hyprland config errors after reload:\n%s" % message, file=sys.stderr)
        return False
    return True


def apply():
    settings = load()
    if not CONFIG.exists():
        save(settings)
    changed = ensure_include()
    changed = write_if_changed(LUA, render(settings)) or changed
    if not changed:
        return "unchanged"
    return "ok" if reload_hyprland() else "written"


def main(argv):
    if len(argv) < 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2

    command = argv[1]

    if command == "state":
        print(json.dumps(load(), sort_keys=True))
        return 0

    if command == "get":
        if len(argv) != 3 or argv[2] not in DEFAULTS:
            print("get needs one of: %s" % ", ".join(DEFAULTS), file=sys.stderr)
            return 2
        print(load()[argv[2]])
        return 0

    if command == "apply":
        print(apply())
        return 0

    if command == "set":
        if len(argv) != 4:
            print("usage: gestures.py set <key> <value>", file=sys.stderr)
            return 2
        key, value = argv[2], argv[3]
        if key not in VALIDATORS:
            print("unknown setting %r (one of: %s)" % (key, ", ".join(DEFAULTS)),
                  file=sys.stderr)
            return 2
        try:
            settings = load()
            settings[key] = VALIDATORS[key](value)
        except BadValue as error:
            print("%s: %s" % (key, error), file=sys.stderr)
            return 2
        save(settings)
        status = apply()
        # The panel parses the first line, so keep diagnostics on stderr.
        print(status)
        print(json.dumps(settings, sort_keys=True))
        return 0

    print("unknown command %r (state, get, apply, set)" % command, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
